  await expect(dialog.getByRole('status')).toHaveText('Profil berhasil disimpan.')
  const firstPhoto = await dialog.getByAltText('Foto profil', { exact: true }).getAttribute('src')
  await input.setInputFiles(await profilePhotoFile(page, '#bada55'))
  await expect(dialog.getByAltText('Pratinjau foto profil')).toBeVisible()
  await dialog.getByRole('button', { name: 'Simpan Profil', exact: true }).click()
  await expect(dialog.getByRole('status')).toHaveText('Profil berhasil disimpan.')
  await expect(dialog.getByAltText('Foto profil', { exact: true })).not.toHaveAttribute('src', firstPhoto!)
  expect(uploads).toBe(2)
  expect(metadataWrites).toEqual([])
  await page.keyboard.press('Escape')
  await expect(trigger.getByRole('img')).toHaveAttribute('src', /^data:image\/jpeg;base64,/)
  await page.reload()
  // Server navigation intentionally strips mocked auth cookies; restore the test session.
  await expect(page).toHaveURL(/\/login$/)
  await page.waitForFunction(() => (document.querySelector('#__nuxt') as any)?.__vue_app__?.$nuxt?.isHydrating === false)
  await page.getByLabel('Alamat email').fill('settings@example.com')
